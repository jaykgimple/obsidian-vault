#!/usr/bin/env python3
"""Dynamic wikilink scanner and fixer for Obsidian vault.

Scans all .md files for [[wikilinks]], checks targets against actual files,
converts broken links to backtick-wrapped text, and logs results.
"""

import re
from pathlib import Path

VAULT = Path("/root/projects/obsidian-vault")

# Patterns that are clearly template/placeholder content, not real links
PLACEHOLDER_PATTERNS = {
    "...", "note name", "untitled", "placeholder", "template",
    "example link", "link name", "page name", "note title",
}

def build_note_index():
    """Return dict mapping normalized note names to their relative paths."""
    notes = {}
    for f in VAULT.rglob("*.md"):
        rel = f.relative_to(VAULT).with_suffix("")
        rel_str = str(rel)
        normalized = rel_str.lower()
        
        # Add full path
        notes[normalized] = rel_str
        # Add stem only
        stem = rel.stem.lower()
        if stem not in notes:
            notes[stem] = rel_str
        # Add normalized with spaces
        spaced = stem.replace("-", " ")
        if spaced not in notes:
            notes[spaced] = rel_str
        # Add normalized with hyphens
        hyphenated = stem.replace(" ", "-")
        if hyphenated not in notes:
            notes[hyphenated] = rel_str
    return notes

# Wikilink regex: [[target]] or [[target|alias]] or [[target#section]]
WIKILINK_RE = re.compile(r'\[\[([^\]\|#]+)(?:#[^\]\|]+)?(?:\|[^\]]+)?\]\]')

def is_placeholder(target):
    """Check if a wikilink target is a template placeholder."""
    normalized = target.strip().lower()
    return normalized in PLACEHOLDER_PATTERNS

def resolve_link(target, note_index):
    """Check if a wikilink target resolves to an existing note. Returns (bool, suggestion)."""
    normalized = target.strip().lower()
    
    # Direct match
    if normalized in note_index:
        return True, None
    
    # Try stem only
    stem = normalized.split("/")[-1] if "/" in normalized else normalized
    if stem in note_index:
        return True, None
    
    # Try common Obsidian slug transformations
    hyphenated = normalized.replace(" ", "-")
    if hyphenated in note_index:
        return True, None
    
    spaced = normalized.replace("-", " ")
    if spaced in note_index:
        return True, None
    
    # Generate suggestion: find similar note
    suggestion = None
    if "agentic" in normalized:
        # Look for similar blog posts
        for key in note_index:
            if key.startswith("10-properties/octogentic/blog/") and normalized.replace("10-properties/octogentic/blog/", "").replace("-", "") in key.replace("-", ""):
                suggestion = note_index[key]
                break
    
    return False, suggestion

def scan_and_fix():
    """Scan all notes and fix broken wikilinks."""
    note_index = build_note_index()
    
    results = {
        "total_notes": 0,
        "total_links": 0,
        "resolved": 0,
        "broken": 0,
        "skipped": 0,
        "fixes": [],
        "unresolved": [],
    }
    
    md_files = sorted(VAULT.rglob("*.md"))
    
    results["total_notes"] = len(md_files)
    
    for filepath in md_files:
        content = filepath.read_text(encoding="utf-8")
        original = content
        
        # Find all wikilinks
        matches = list(WIKILINK_RE.finditer(content))
        
        for match in reversed(matches):  # reverse to preserve positions
            full_match = match.group(0)
            target = match.group(1).strip()
            
            # Skip placeholders
            if is_placeholder(target):
                results["skipped"] += 1
                continue
            
            results["total_links"] += 1
            
            resolved, suggestion = resolve_link(target, note_index)
            
            if resolved:
                results["resolved"] += 1
            else:
                results["broken"] += 1
                # Replace with backtick-wrapped text
                replacement = f"`{target}`"
                content = content[:match.start()] + replacement + content[match.end():]
                
                rel_path = str(filepath.relative_to(VAULT))
                results["fixes"].append({
                    "file": rel_path,
                    "link": target,
                    "original": full_match,
                    "suggestion": suggestion,
                })
        
        if content != original:
            filepath.write_text(content, encoding="utf-8")
    
    return results

def generate_log(results):
    """Generate the maintenance log markdown."""
    lines = [
        "# Vault Maintenance Log: 2026-10-26",
        "",
        "> Generated by CoS daily maintenance cron",
        "> Date: 2026-10-26 (Monday, October 26, 2026)",
        "",
        "## Summary",
        f"- Total notes: {results['total_notes']}",
        f"- Total wikilink occurrences: {results['total_links']}",
        f"- Resolved links: {results['resolved']}",
        f"- Placeholder/template links skipped: {results['skipped']}",
        f"- Broken/ambiguous links found: {results['broken']}",
        f"- Fixes applied: {len(results['fixes'])}",
        "- Daily note: 00-DAILY/2026-10-26.md (already existed)",
        "",
    ]
    
    if results["fixes"]:
        lines.append("## Fixes Applied")
        lines.append("")
        for fix in results["fixes"]:
            suggestion_str = f" (suggested: {fix['suggestion']})" if fix['suggestion'] else ""
            lines.append(f"- `{fix['file']}`: `{fix['original']}` → `{fix['link']}`{suggestion_str}")
        lines.append("")
    else:
        lines.append("## Fixes Applied")
        lines.append("- No broken links found. All wikilinks resolve correctly.")
        lines.append("")
    
    lines.append("## Unresolved Links (forward references / known acceptable)")
    if results["unresolved"]:
        for u in results["unresolved"]:
            lines.append(f"- `{u}`")
    else:
        lines.append("- None")
    lines.append("")
    
    lines.append("## Notes")
    lines.append("- 00-DAILY/2026-10-26 daily note already present, no creation needed")
    lines.append("- All vault subdirectories scanned: 00-DAILY, 00-META, 10-PROPERTIES, 20-AGENTS, 30-PATTERNS, 40-LOGS")
    lines.append("- Template placeholders (e.g. [[...]], [[Note Name]]) are not flagged")
    lines.append("")
    
    return "\n".join(lines)

def main():
    print("Building note index...")
    note_index = build_note_index()
    print(f"  Found {len(note_index)} normalized note references")
    
    print("Scanning and fixing wikilinks...")
    results = scan_and_fix()
    
    print(f"  Total notes: {results['total_notes']}")
    print(f"  Total links: {results['total_links']}")
    print(f"  Resolved: {results['resolved']}")
    print(f"  Skipped (placeholders): {results['skipped']}")
    print(f"  Broken: {results['broken']}")
    print(f"  Fixes: {len(results['fixes'])}")
    
    if results["fixes"]:
        print("\nFixed links:")
        for fix in results["fixes"]:
            sugg = f" -> suggest: {fix['suggestion']}" if fix['suggestion'] else ""
            print(f"  {fix['file']}: {fix['original']} -> `{fix['link']}`{sugg}")
    
    # Write log
    log_content = generate_log(results)
    log_path = VAULT / "40-LOGS" / "vault-analysis-latest.md"
    log_path.write_text(log_content, encoding="utf-8")
    print(f"\nLog written to {log_path}")

if __name__ == "__main__":
    main()
